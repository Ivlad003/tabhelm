#!/usr/bin/env node
// Registers the TabHelm native messaging host for Chrome-family browsers.
// Chrome starts native hosts with a minimal environment, so we bake the
// current PATH into a wrapper script; otherwise `claude`, `opencode` etc.
// installed under ~/.local/bin would not be found.

import { createHash } from 'node:crypto';
import { chmodSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { homedir, platform } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HOST_NAME = 'com.tabhelm.host';
const hostRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const repoRoot = join(hostRoot, '..');

const manifest = JSON.parse(readFileSync(join(repoRoot, 'extension', 'manifest.json'), 'utf8'));
const extensionId = extensionIdFromKey(manifest.key);

const wrapper = join(hostRoot, 'tabhelm-host.sh');
writeFileSync(
  wrapper,
  `#!/bin/sh\n# Generated by host/scripts/install.js\nexport PATH=${JSON.stringify(process.env.PATH)}\nexec ${JSON.stringify(process.execPath)} ${JSON.stringify(join(hostRoot, 'src', 'native-host.js'))} "$@"\n`,
);
chmodSync(wrapper, 0o755);

const hostManifest = {
  name: HOST_NAME,
  description: 'TabHelm bridge between the Chrome side panel and terminal coding agents',
  path: wrapper,
  type: 'stdio',
  allowed_origins: [`chrome-extension://${extensionId}/`],
};

// `--user-data-dir <dir>` installs only into a custom Chrome profile (used by tests).
const customDirArg = process.argv.indexOf('--user-data-dir');
const customDir = customDirArg > 0 ? process.argv[customDirArg + 1] : null;

const home = customDir ? '/' : homedir();
const targets = customDir
  ? [customDir]
  : platform() === 'darwin'
    ? [
        'Library/Application Support/Google/Chrome',
        'Library/Application Support/Google/Chrome Beta',
        'Library/Application Support/Chromium',
        'Library/Application Support/BraveSoftware/Brave-Browser',
        'Library/Application Support/Microsoft Edge',
      ]
    : [
        '.config/google-chrome',
        '.config/google-chrome-beta',
        '.config/chromium',
        '.config/BraveSoftware/Brave-Browser',
        '.config/microsoft-edge',
      ];

let installed = 0;
for (const rel of targets) {
  const browserDir = join(home, rel);
  if (!existsSync(browserDir)) continue;
  const dir = join(browserDir, 'NativeMessagingHosts');
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, `${HOST_NAME}.json`), JSON.stringify(hostManifest, null, 2));
  console.log(`✓ ${join(dir, `${HOST_NAME}.json`)}`);
  installed++;
}

if (!installed) {
  console.error('No Chrome-family browser profile directory found. Is Chrome installed?');
  process.exit(1);
}
console.log(`\nExtension ID: ${extensionId}`);
console.log(`Load the unpacked extension from: ${join(repoRoot, 'extension')}`);

// Chrome derives unpacked extension IDs from the manifest "key":
// sha256 of the DER public key, first 32 hex chars mapped 0-f -> a-p.
function extensionIdFromKey(key) {
  const hash = createHash('sha256').update(Buffer.from(key, 'base64')).digest('hex').slice(0, 32);
  return [...hash].map((c) => String.fromCharCode(97 + parseInt(c, 16))).join('');
}
